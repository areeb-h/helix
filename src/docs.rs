//! The per-name documentation table: one signature, one sentence, ONE runnable
//! example, and the semantic surprises — the content `helix describe` and
//! `helix doc` surface. The field review's highest-ranked ask: ten wrong
//! factual claims about Helix were each one query away, and the query answered
//! with a bare name.
//!
//! Three rules keep this table honest:
//!
//! 1. **Every example with an `example_out` is EXECUTED by the gate** (the
//!    `doc_table_examples_all_run` CLI test wraps it in `print(...)` exactly as
//!    the doc-example runner does) — the documentation cannot drift from the
//!    implementation. An empty `example_out` means shown-not-run (effectful,
//!    feature-gated, or nondeterministic).
//! 2. **Coverage is a guard test**, both directions: every builtin and every
//!    method of every type has an entry, and every entry names something real.
//! 3. **`notes` is the surprise channel**: the one sentence a reader needs
//!    BEFORE using the name — last-wins, raises-on, seed-threaded — the
//!    behaviours that produce silently wrong code rather than a crash. Empty
//!    means "no surprises"; that emptiness is a claim, so a surprise found in
//!    the field belongs here in the same commit that answers the report.

/// One name's documentation. All strings are static and prose-free enough to
/// print in one terminal line each.
pub struct DocEntry {
    pub name: &'static str,
    /// The call shape, human-written: `split_once(sep)`.
    pub sig: &'static str,
    /// One sentence of what it does.
    pub doc: &'static str,
    /// One expression a caller would write (no `print` — the tooling wraps it).
    pub example: &'static str,
    /// Exact stdout of `print(<example>)`, or "" for shown-not-run.
    pub example_out: &'static str,
    /// A semantic surprise worth reading BEFORE use, or "".
    pub notes: &'static str,
}

