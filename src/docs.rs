/// The entry for a free function, if written yet.
pub fn builtin_doc(name: &str) -> Option<&'static DocEntry> {
    BUILTIN_DOCS.iter().find(|d| d.name == name)
}

/// The entry for `ty.name(...)`, if written yet.
pub fn method_doc(ty: &str, name: &str) -> Option<&'static DocEntry> {
    METHOD_DOCS.iter().find(|(t, d)| *t == ty && d.name == name).map(|(_, d)| d)
}

/// Parse a `sig` string's parameter list into a (required, maximum) arity — the
/// checker's method-arity gate reads the SAME signatures the reference prints,
/// so the two cannot drift. `?` marks an optional parameter, `...` a variadic
/// tail (no maximum). `None` = the sig has no parameter list to read.
pub fn sig_arity(sig: &str) -> Option<(usize, Option<usize>)> {
    let inner = sig.split_once('(')?.1.strip_suffix(')')?.trim();
    if inner.is_empty() {
        return Some((0, Some(0)));
    }
    let (mut required, mut total, mut variadic) = (0usize, 0usize, false);
    for p in inner.split(',') {
        let p = p.trim();
        if p == "..." {
            variadic = true;
            continue;
        }
        total += 1;
        if !p.ends_with('?') {
            required += 1;
        }
    }
    Some((required, if variadic { None } else { Some(total) }))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Coverage, both directions: every builtin has an entry, every entry names
    /// a real builtin, no duplicates.
    #[test]
    fn every_builtin_has_a_doc_entry_and_no_orphans() {
        for b in crate::registry::BUILTINS {
            assert!(builtin_doc(b.path).is_some(), "no docs entry for builtin `{}`", b.path);
        }
        for (i, d) in BUILTIN_DOCS.iter().enumerate() {
            assert!(
                crate::registry::lookup(d.name).is_some(),
                "docs entry for unknown builtin `{}`",
                d.name
            );
            assert!(
                !BUILTIN_DOCS[..i].iter().any(|e| e.name == d.name),
                "duplicate docs entry `{}`",
                d.name
            );
        }
    }

    /// Same rule for every method of every type (universal methods live under
    /// the pseudo-type "Any").
    #[test]
    fn every_method_has_a_doc_entry_and_no_orphans() {
        for (ty, ms) in crate::registry::type_method_tables() {
            for m in ms {
                assert!(method_doc(ty, m).is_some(), "no docs entry for {ty}.{m}");
            }
        }
        for u in crate::registry::UNIVERSAL_METHODS {
            assert!(method_doc("Any", u).is_some(), "no docs entry for universal `{u}`");
        }
        for (i, (ty, d)) in METHOD_DOCS.iter().enumerate() {
            let known = (*ty == "Any" && crate::registry::UNIVERSAL_METHODS.contains(&d.name))
                || crate::registry::type_method_tables()
                    .iter()
                    .any(|(t, ms)| t == ty && ms.contains(&d.name));
            assert!(known, "docs entry for unknown method {ty}.{}", d.name);
            assert!(
                !METHOD_DOCS[..i].iter().any(|(t2, e)| t2 == ty && e.name == d.name),
                "duplicate docs entry {ty}.{}",
                d.name
            );
        }
    }
}
